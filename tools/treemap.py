#!/usr/bin/env python3

"""Render the local treemap from objdiff reports."""

import argparse
import hashlib
import json
import os
import re
import sys
import webbrowser
from typing import Any, Dict, List, Optional, Tuple

script_dir = os.path.dirname(os.path.realpath(__file__))
root_dir = os.path.abspath(os.path.join(script_dir, ".."))
sys.path.insert(0, script_dir)
import versions as ver  # noqa: E402
import treemap_layout  # noqa: E402

SVG_ATTRIBUTES = {"width": "1000", "height": "500", "viewBox": "0 0 1000 500"}
RECT_ATTRIBUTES = {"stroke": "#fff", "stroke-width": "1", "vector-effect": "non-scaling-stroke"}

# First match wins, checked against the path under the module, like
# TRK_MINNOW_DOLPHIN/msghndlr. Named units that match nothing land in game.
LIBRARY_RULES = [
    ("Runtime", re.compile(r"^Runtime")),
    ("MSL", re.compile(r"^MSL")),
    ("TRK", re.compile(r"^(TRK|MetroTRK)")),
    ("SDK", re.compile(r"^(dolphin|THP|sdk)", re.I)),
    ("HSD", re.compile(r"^(sysdolphin|baselib|HSD)", re.I)),
]
GROUP_ORDER = ["Runtime", "MSL", "TRK", "SDK", "HSD", "game", "unmapped DOL", "RELs"]

# version folders like GGTE01 or GGTJ01_01, the fourth letter is the region and
# the _NN on the end, when there is one, is the disc revision
GAME_ID = re.compile(r"^[A-Z0-9]{6}(?:_(\d{2}))?$")
REGIONS = {"J": "Japan", "E": "USA", "P": "Europe"}

# dtk default names like fn_80012345, fn_16_AC, dtor_80008DC8
PLACEHOLDER_FN = re.compile(r"^(fn|dtor|ctor|lbl)_[0-9A-Fa-f_]+$")


def library_for(path: str) -> str:
    for name, rule in LIBRARY_RULES:
        if rule.search(path):
            return name
    return "game"


def num(v: Any) -> int:
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def unit_from_report(u: Dict[str, Any]) -> Dict[str, Any]:
    meta = u.get("metadata", {})
    full = u["name"]
    module, _, path = full.partition("/")
    module = meta.get("module_name", module)
    auto = bool(meta.get("auto_generated", False))
    m = u.get("measures", {})

    code = num(m.get("total_code"))
    fuzzy = float(m.get("fuzzy_match_percent", 0) or 0)
    matched = num(m.get("matched_code"))
    complete = bool(meta.get("complete", False))

    # auto units report 100% since they link the original asm, so only trust
    # these numbers on named units
    if auto:
        status = "auto"
    elif complete:
        status = "linked"
    # a fully matched unit just hasn't been flipped to linked yet, so it stays
    # in progress at the top of the shading
    elif fuzzy > 0 or matched > 0:
        status = "fuzzy"
    else:
        status = "named"

    if module != "main":
        group = "RELs"
    elif auto:
        group = "unmapped DOL"
    else:
        group = library_for(path)

    sections = [
        [s["name"], num(s.get("metadata", {}).get("virtual_address")), num(s["size"])]
        for s in u.get("sections", [])
    ]
    fns = [f["name"] for f in u.get("functions", [])]
    placeholder = sum(1 for f in fns if PLACEHOLDER_FN.match(f))
    # name, address, size, match % for the unit page. RELs have no real address,
    # so fall back to the offset in the section
    funcs = []
    for f in u.get("functions", []):
        fm = f.get("metadata", {})
        addr = num(fm.get("virtual_address")) or num(f.get("address"))
        pct = 0.0 if auto else round(float(f.get("fuzzy_match_percent", 0) or 0), 2)
        funcs.append([fm.get("demangled_name") or f["name"], addr, num(f.get("size")), pct])

    return {
        "name": path or full,
        "full": full,
        "module": module,
        "group": group,
        "status": status,
        "code": code,
        "data": num(m.get("total_data")),
        "fuzzy": 0 if auto else fuzzy,
        "matched_code": 0 if auto else matched,
        "matched_data": 0 if auto else num(m.get("matched_data")),
        "complete": complete and not auto,
        "fns": num(m.get("total_functions")),
        "fns_matched": 0 if auto else num(m.get("matched_functions")),
        "sections": sections,
        "fn_named": len(fns) - placeholder,
        "fn_placeholder": placeholder,
        "funcs": funcs,
    }


def units_from_config(cfg: Dict[str, Any]) -> List[Dict[str, Any]]:
    # less detail than the report: no addresses, no functions
    out = []
    for mod in [cfg, *cfg.get("modules", [])]:
        module = mod.get("name", "main")
        for u in mod.get("units", []):
            auto = bool(u.get("autogenerated"))
            path = re.sub(r"\.(c|cc|cp|cpp|s)$", "", u["name"])
            if module != "main":
                group = "RELs"
            elif auto:
                group = "unmapped DOL"
            else:
                group = library_for(path)
            out.append({
                "name": path,
                "full": f"{module}/{path}",
                "module": module,
                "group": group,
                "status": "auto" if auto else "named",
                "code": num(u.get("code_size")),
                "data": num(u.get("data_size")),
                "fuzzy": 0,
                "matched_code": 0,
                "matched_data": 0,
                "complete": False,
                "fns": 0,
                "fns_matched": 0,
                "sections": [],
                "fn_named": 0,
                "fn_placeholder": 0,
                "funcs": [],
            })
    return out


def load_units(build_dir: str, report: Optional[str] = None) -> Tuple[List[Dict[str, Any]], str]:
    report = report or os.path.join(build_dir, "report.json")
    config = os.path.join(build_dir, "config.json")
    if os.path.exists(report):
        with open(report) as f:
            data = json.load(f)
        return [unit_from_report(u) for u in data["units"]], report
    if os.path.exists(config):
        with open(config) as f:
            data = json.load(f)
        return units_from_config(data), config
    sys.exit(f"no report.json or config.json in {build_dir}, run ninja first")


def revision_of(version: str) -> Optional[int]:
    m = GAME_ID.match(version)
    return int(m.group(1)) if m and m.group(1) else None


def find_versions(building: str) -> List[str]:
    # every other version only counts once ninja has written its report.json, so
    # each map comes from the same data. the config.json fallback is only for the
    # version being built, before its first full build. listed in configure.py order
    build = os.path.join(root_dir, "build")
    found = {
        d for d in os.listdir(build)
        if GAME_ID.match(d) and os.path.exists(os.path.join(build, d, "report.json"))
    } if os.path.isdir(build) else set()
    found.add(building)
    order = ver.versions()
    return sorted(found, key=lambda v: (order.index(v) if v in order else len(order), v))


def render_page(payload):
    treemap_layout.prepare(payload)
    payload["map_style"] = {"svg": SVG_ATTRIBUTES, "rect": RECT_ATTRIBUTES}
    with open(os.path.join(script_dir, "treemap_template.html"), encoding="utf-8") as f:
        page = f.read()
    palette = "\n".join(f"  --{key}: {value};" for key, value in treemap_layout.PALETTE.items())
    page = page.replace("/*__PALETTE__*/", palette)
    if payload.get("live") is not False:
        content = [{k: x for k, x in v.items() if k != "generated"} for v in payload["versions"]]
        payload["stamp"] = hashlib.sha1((json.dumps([content, payload["map_style"]]) + page).encode()).hexdigest()[:16]
    blob = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return page.replace("/*__DATA__*/null", blob)


def main(argv: Optional[List[str]] = None) -> None:
    parser = argparse.ArgumentParser(description="Write a local unit treemap page.")
    parser.add_argument("--version", default=ver.current(), help="version being built, default the configured one")
    parser.add_argument("--default", default=ver.default_version(),
                        help="version the page opens on when it's built, default from configure.py")
    parser.add_argument("--report", help="report path for --version, default build/<version>/report.json")
    parser.add_argument("-o", "--output", help="output path, default build/treemap.html")
    parser.add_argument("--open", action="store_true", help="open the page when done")
    args = parser.parse_args(argv)

    versions = []
    for v in find_versions(args.version):
        report = args.report if v == args.version else None
        units, source = load_units(os.path.join(root_dir, "build", v), report)
        versions.append({
            "version": v,
            "region": REGIONS.get(v[3:4], ""),
            "revision": revision_of(v),
            "source": os.path.relpath(source, root_dir),
            "generated": os.path.getmtime(source),
            "units": units,
        })
    out_path = args.output or os.path.join(root_dir, "build", "treemap.html")

    payload: Dict[str, Any] = {
        # USA when it has a report, otherwise the one being built
        "default": args.default if any(v["version"] == args.default for v in versions) else args.version,
        "groups": GROUP_ORDER,
        "versions": versions,
    }
    page = render_page(payload)

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write(page)
    stamp_path = os.path.splitext(out_path)[0] + "_stamp.js"
    with open(stamp_path, "w") as f:
        f.write(f"window.TREEMAP_STAMP = {payload['stamp']!r};\n")

    for v in versions:
        named = sum(1 for u in v["units"] if u["status"] != "auto")
        print(f"{v['version']}: {len(v['units'])} units, {named} named, from {v['source']}")
    print(f"wrote {os.path.relpath(out_path, root_dir)}")
    if args.open:
        webbrowser.open("file://" + os.path.abspath(out_path))


if __name__ == "__main__":
    main()
